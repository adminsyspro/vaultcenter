import assert from 'node:assert/strict';
import {translate as t, setLanguage, getLocale, preferredLanguage, isPlural} from '../src/lib/i18n.ts';
import core from '../src/lib/locales/en-core.ts';
import media from '../src/lib/locales/en-media.ts';
import storage from '../src/lib/locales/en-storage.ts';
import admin from '../src/lib/locales/en-admin.ts';
import api from '../src/lib/locales/en-api.ts';
import controllers from '../src/lib/locales/en-controllers.ts';
const seen=new Map();
const parameters=value=>[...value.matchAll(/\{(\w+)\}/g)].map(match=>match[1]).sort();
for(const catalog of [core,media,storage,admin,api,controllers])for(const [fr,en] of Object.entries(catalog)){
 assert.ok(en.trim(),`Empty translation: ${fr}`);
 assert.deepEqual(parameters(en),parameters(fr),`Placeholder mismatch: ${fr}`);
 if(seen.has(fr))assert.equal(en,seen.get(fr),`Conflicting translation: ${fr}`);
 seen.set(fr,en);
}
assert.equal(preferredLanguage('fr',['en-GB']),'fr');
assert.equal(preferredLanguage('en',['fr-FR']),'en');
assert.equal(preferredLanguage(null,['en-US']),'en');
assert.equal(preferredLanguage(null,['de-DE','en-GB']),'fr');
assert.equal(preferredLanguage('bad',[]),'fr');
setLanguage('en');
assert.equal(getLocale(),'en-GB');
assert.equal(isPlural(0),true);assert.equal(isPlural(1),false);assert.equal(isPlural(2),true);
assert.equal(t('Erreur HTTP {status}',{status:404}),'HTTP error 404');
assert.equal(t('Erreur HTTP 404'),'HTTP error 404');
assert.equal(t('Lecteur 12'),'Drive 12');
assert.equal(t('Lecteur LTO · 01'),'LTO drive · 01');
assert.equal(t('Lecteur principal Alice'),'Lecteur principal Alice');
assert.equal(t('CVT004L8'),'CVT004L8');
assert.equal(t('diagnostic unknown 0x12'),'diagnostic unknown 0x12');
assert.equal(t('permission denied'),'You do not have the required permissions.');
const text=t('Associer dans PBS le changeur {changer} et le lecteur {drive}, puis reprendre l’activation. Le bail reste réservé.',{changer:'robot-A',drive:'drive-B'});
assert.ok(text.includes('robot-A')&&text.includes('drive-B')&&!text.includes('Associer'));
const nested='Le bucket de la nouvelle période n’a pas pu être utilisé. Le bucket vc-a a été créé vide, mais il n’a pas été activé. La destination active a changé. Vous pouvez l’utiliser depuis les options avancées. L’envoi n’a pas été lancé.';
assert.equal(t(nested),'The new period\'s bucket could not be used. The bucket vc-a was created empty, but it was not activated. The active destination has changed. You can use it from the advanced options. The export was not started.');
assert.equal(t('Le bucket de la nouvelle période n’a pas été créé. Le fournisseur a refusé les identifiants. Corrigez la connexion, puis réessayez. L’envoi n’a pas été lancé.'),'The new period\'s bucket was not created. The provider rejected the credentials. Fix the connection, then try again. The export was not started.');
assert.equal(t('L’archivage automatique a été refusé. Raison inconnue du catalogue. Une nouvelle tentative aura lieu demain.'),'Automatic archiving was refused. Raison inconnue du catalogue. A new attempt will take place tomorrow.');
assert.equal(t('Le bucket de la nouvelle période n’a pas pu être utilisé. Le bucket vc-a existe déjà et contient des données. Il ne sera pas utilisé. Le prochain envoi proposera un nouveau nom. L’envoi n’a pas été lancé.'),'The new period\'s bucket could not be used. The bucket vc-a already exists and contains data. It will not be used. The next export will propose a new name. The export was not started.');
assert.equal(t('Le bucket vc-a existe déjà et contient des données. Il ne sera pas utilisé.'),'The bucket vc-a already exists and contains data. It will not be used.');
assert.equal(t('Demande acceptée par OVH. Le suivi de l’archivage continue automatiquement.'),'Request accepted by OVH. Archive tracking continues automatically.');
setLanguage('fr');
assert.equal(t(t(nested)),nested);
setLanguage('en');
assert.equal(t(t(nested)),t(nested));
setLanguage('fr');
assert.equal(getLocale(),'fr-FR');assert.equal(isPlural(0),false);
assert.equal(t('HTTP error 404'),'Erreur HTTP 404');
assert.equal(t('Drive 12'),'Lecteur 12');
assert.equal(t(text),'Associer dans PBS le changeur robot-A et le lecteur drive-B, puis reprendre l’activation. Le bail reste réservé.');
assert.equal(t('Erreur HTTP {status}',{status:'<script>$&</script>'}),'Erreur HTTP <script>$&</script>');
console.log(`PASS i18n unit: ${seen.size} catalog messages, placeholders, conflicts, persistence choices, plurals, dynamic error translation and opaque names.`);
