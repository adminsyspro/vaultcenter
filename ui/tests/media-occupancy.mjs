import assert from 'node:assert/strict';
import {ageTelemetry,occupancy} from '../src/lib/telemetry.ts';
import {demoId,demoMedia,telemetryFixture} from './helpers/telemetry-fixtures.mjs';
const media={...demoMedia()[0],state:'writable',bytes_written:0,capacity_bytes:1000};
const observation={...telemetryFixture().media[0],local_size_bytes:450};
assert.equal(occupancy(media,observation).percent,45,'Live local size must replace the empty writable catalogue');
assert.equal(occupancy(media,observation).label,'Occupation locale estimée');
assert.equal(occupancy(media,{...observation,local_size_bytes:0}).percent,0);
assert.equal(occupancy(media,{...observation,local_size_bytes:1500}).percent,100);
assert.equal(occupancy(media,{...observation,logical_used_bytes:200,logical_capacity_bytes:800}).percent,25);
assert.equal(occupancy({...media,state:'exported',bytes_written:750},observation).percent,75,'Eviction must not shrink archived occupancy');
assert.equal(occupancy(media,{...observation,barcode:'OTHER'}).percent,0);
assert.equal(occupancy(media,{...observation,local_size_bytes:-1}).percent,0);
assert.equal(occupancy({...media,capacity_bytes:0},observation).percent,null);
const now=Date.now();
const stale=ageTelemetry(telemetryFixture(demoId,'stale',now),now);
assert.equal(occupancy(media,stale.media[0]).percent,0,'Expired telemetry must fall back to the catalogue');
assert.equal(occupancy({...media,bytes_written:750}).percent,75);
console.log('PASS occupancy: live, logical priority, empty/full/unknown, archived, mismatched barcode and stale fallback');
